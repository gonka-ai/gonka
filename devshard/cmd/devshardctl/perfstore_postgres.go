func (s *postgresPerfStore) ImportRequestAccounting(ctx context.Context, sourcePath, escrowID string) (int64, int64, error) {
	if strings.TrimSpace(sourcePath) == "" || strings.TrimSpace(escrowID) == "" {
		return 0, 0, nil
	}
	ctx, cancel := context.WithTimeout(ctx, pgtimeouts.ImportTimeout())
	defer cancel()
	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return 0, 0, fmt.Errorf("begin request accounting import of %s: %w", escrowID, err)
	}
	defer func() { _ = tx.Rollback(ctx) }()
	requests, attempts, err := forEachImportedAccountingPage(ctx, sourcePath, escrowID, importedAccountingPageVisitor{
		requests: func(page []importedAccountingRequest) error {
			batch := &pgx.Batch{}
			for _, imported := range page {
				rec := imported.record
				batch.Queue(`INSERT INTO request_accounting (request_id, escrow_id, model, started_at, completed_at, outcome, decision, winner_nonce)
					 VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
					 ON CONFLICT (request_id, escrow_id) DO UPDATE SET
					   model = EXCLUDED.model,
					   started_at = EXCLUDED.started_at,
					   completed_at = EXCLUDED.completed_at,
					   outcome = EXCLUDED.outcome,
					   decision = EXCLUDED.decision,
					   winner_nonce = EXCLUDED.winner_nonce`,
					rec.RequestID, rec.EscrowID, rec.Model, imported.startedAt, imported.completedAt, rec.Outcome, rec.Decision, int64(rec.WinnerNonce))
			}
			return tx.SendBatch(ctx, batch).Close()
		},
		attempts: func(page []importedAccountingAttempt) error {
			batch := &pgx.Batch{}
			for _, imported := range page {
				attempt := imported.attempt
				batch.Queue(`INSERT INTO request_accounting_attempts (
					   request_id, escrow_id, nonce, host_idx, participant_key, probe, winner, created_at
					 ) VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
					 ON CONFLICT (request_id, escrow_id, nonce) DO UPDATE SET
					   host_idx = EXCLUDED.host_idx,
					   participant_key = EXCLUDED.participant_key,
					   probe = EXCLUDED.probe,
					   winner = EXCLUDED.winner,
					   created_at = EXCLUDED.created_at`,
					attempt.RequestID, attempt.EscrowID, int64(attempt.Nonce), attempt.HostIdx, attempt.ParticipantKey, imported.probe, imported.winner, imported.createdAt)
			}
			return tx.SendBatch(ctx, batch).Close()
		},
	})
	if err != nil {
		return 0, 0, fmt.Errorf("import request accounting of %s: %w", escrowID, err)
	}
	if err := tx.Commit(ctx); err != nil {
		return 0, 0, fmt.Errorf("commit request accounting import of %s: %w", escrowID, err)
	}
	return requests, attempts, nil
}

func (s *postgresPerfStore) FindAccountingRequest(ctx context.Context, requestID, escrowID string) (RequestAccountingRecord, bool, error) {
	ctx, cancel := s.opCtx(ctx)
	defer cancel()
	return resolveAccountingRequest(ctx, s, requestID, escrowID)
}

func (s *postgresPerfStore) findAccountingRequestDirect(ctx context.Context, requestID, escrowID string) (RequestAccountingRecord, bool, error) {
	var (
		rec         RequestAccountingRecord
		startedAt   string
		completedAt string
		winnerNonce int64
	)
	err := s.pool.QueryRow(ctx,
		`SELECT request_id, escrow_id, model, started_at, completed_at, outcome, decision, winner_nonce
		 FROM request_accounting
		 WHERE request_id = $1 AND escrow_id = $2`,
		requestID, escrowID,
	).Scan(&rec.RequestID, &rec.EscrowID, &rec.Model, &startedAt, &completedAt, &rec.Outcome, &rec.Decision, &winnerNonce)
	if errors.Is(err, pgx.ErrNoRows) {
		return RequestAccountingRecord{}, false, nil
	}
	if err != nil {
		return RequestAccountingRecord{}, false, fmt.Errorf("find request accounting %s/%s: %w", escrowID, requestID, err)
	}
	rec.StartedAt = strToTime(startedAt)
	rec.CompletedAt = strToTime(completedAt)
	rec.WinnerNonce = uint64(winnerNonce)

	attempts, err := s.findAccountingAttempts(ctx, requestID, escrowID)
	if err != nil {
		return RequestAccountingRecord{}, false, err
	}
	rec.Attempts = attempts
	return rec, true, nil
}

func (s *postgresPerfStore) findAccountingAlias(ctx context.Context, requestID, escrowID string) (requestAccountingAlias, bool, error) {
	var alias requestAccountingAlias
	err := s.pool.QueryRow(ctx,
		`SELECT source_request_id, source_escrow_id, reason
		 FROM request_accounting_aliases
		 WHERE request_id = $1 AND escrow_id = $2`,
		requestID, escrowID,
	).Scan(&alias.sourceRequestID, &alias.sourceEscrowID, &alias.reason)
	if errors.Is(err, pgx.ErrNoRows) {
		return requestAccountingAlias{}, false, nil
	}
	if err != nil {
		return requestAccountingAlias{}, false, fmt.Errorf("find request accounting alias %s/%s: %w", escrowID, requestID, err)
	}
	return alias, true, nil
}

func (s *postgresPerfStore) findAccountingAttempts(ctx context.Context, requestID, escrowID string) ([]RequestAccountingAttempt, error) {
	rows, err := s.pool.Query(ctx,
		`SELECT request_id, escrow_id, nonce, host_idx, participant_key, probe, winner, created_at
		 FROM request_accounting_attempts
		 WHERE request_id = $1 AND escrow_id = $2
		 ORDER BY nonce ASC`,
		requestID, escrowID,
	)
	if err != nil {
		return nil, fmt.Errorf("find request accounting attempts %s/%s: %w", escrowID, requestID, err)
	}
	defer rows.Close()

	var attempts []RequestAccountingAttempt
	for rows.Next() {
		var (
			attempt       RequestAccountingAttempt
			nonce         int64
			probe, winner int16
			createdAt     string
		)
		if err := rows.Scan(&attempt.RequestID, &attempt.EscrowID, &nonce, &attempt.HostIdx, &attempt.ParticipantKey, &probe, &winner, &createdAt); err != nil {
			return nil, fmt.Errorf("find request accounting attempts %s/%s: %w", escrowID, requestID, err)
		}
		attempt.Nonce = uint64(nonce)
		attempt.Probe = probe != 0
		attempt.Winner = winner != 0
		attempt.CreatedAt = strToTime(createdAt)
		attempts = append(attempts, attempt)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("find request accounting attempts %s/%s: %w", escrowID, requestID, err)
	}
	return attempts, nil
}

func (s *postgresPerfStore) hostSampleBoundaryBatch(ctx context.Context, stopBefore time.Time, beforeID int64, limit int) (boundary, lastScannedID int64, scanned int, err error) {
	ctx, cancel := s.opCtx(ctx)
	defer cancel()
	rows, err := s.pool.Query(ctx, `SELECT id, send_time, source_escrow FROM perf_host_samples WHERE id < $1 ORDER BY id DESC LIMIT $2`, beforeID, limit)
	if err != nil {
		return 0, beforeID, 0, fmt.Errorf("read perf sample boundary: %w", err)
	}
	defer rows.Close()
	lastScannedID = beforeID
	for boundary == 0 && rows.Next() {
		var (
			id           int64
			sendTimeText string
			sourceEscrow string
		)
		if err := rows.Scan(&id, &sendTimeText, &sourceEscrow); err != nil {
			return 0, beforeID, 0, fmt.Errorf("read perf sample boundary: %w", err)
		}
		scanned++
		lastScannedID = id
		if isPastSampleWindow(strToTime(sendTimeText), sourceEscrow, stopBefore) {
			boundary = id
		}
	}
	rows.Close()
	if err := rows.Err(); err != nil {
		return 0, beforeID, 0, fmt.Errorf("read perf sample boundary: %w", err)
	}
	return boundary, lastScannedID, scanned, nil
}

func (s *postgresPerfStore) requestLogRetentionBoundary(ctx context.Context) (int64, error) {
	ctx, cancel := s.opCtx(ctx)
	defer cancel()
	var boundary int64
	err := s.pool.QueryRow(ctx, `SELECT id FROM perf_request_log ORDER BY id DESC LIMIT 1 OFFSET $1`, requestLogSize).Scan(&boundary)
	if errors.Is(err, pgx.ErrNoRows) {
		return 0, nil
	}
	if err != nil {
		return 0, fmt.Errorf("read perf request log boundary: %w", err)
	}
	return boundary, nil
}

func (s *postgresPerfStore) deleteHostSamplesUpTo(ctx context.Context, boundaryID int64, limit int) (int64, error) {
	return s.deleteRowsUpTo(ctx, `DELETE FROM perf_host_samples WHERE id IN (SELECT id FROM perf_host_samples WHERE id <= $1 ORDER BY id LIMIT $2)`, boundaryID, limit)
}

func (s *postgresPerfStore) deleteRequestLogUpTo(ctx context.Context, boundaryID int64, limit int) (int64, error) {
	return s.deleteRowsUpTo(ctx, `DELETE FROM perf_request_log WHERE id IN (SELECT id FROM perf_request_log WHERE id <= $1 ORDER BY id LIMIT $2)`, boundaryID, limit)
}

func (s *postgresPerfStore) deleteRowsUpTo(ctx context.Context, statement string, boundaryID int64, limit int) (int64, error) {
	ctx, cancel := s.opCtx(ctx)
	defer cancel()
	tag, err := s.pool.Exec(ctx, statement, boundaryID, limit)
	if err != nil {
		return 0, fmt.Errorf("delete perf rows: %w", err)
	}
	return tag.RowsAffected(), nil
}
