#!/usr/bin/env bash
# Build versiond + versiond-router + devshardd from the previous participant
# line. Phase 6 uses the images for mixed-hop coverage; the binary is kept as a
# separate artifact so current versiond can be exercised with a real old child.
#
#   make -C devshard/testenv build-baseline-infra
#
# Tags (override with env):
#   devshard-versiond:0.2.15-v5
#   devshard-versiond-router:0.2.15-v5
#
# BASELINE_BRANCH selects the archived ref (default devshard-0.2.15-v5).
# BASELINE_SKIP_DEVSHARDD=1 builds only the two images.
# BASELINE_PIN_FILE and BASELINE_CHECKOUT override the record and extract paths.
#
# Sources are extracted with git archive (no extra worktree).
set -euo pipefail

root="$(CDPATH='' cd -- "$(dirname "$0")/../../.." && pwd)"
cd "$root"

BASELINE_BRANCH="${BASELINE_BRANCH:-devshard-0.2.15-v5}"
BASELINE_REF="${BASELINE_REF:-}"
VERSIOND_IMAGE="${BASELINE_VERSIOND_IMAGE:-devshard-versiond:0.2.15-v5}"
ROUTER_IMAGE="${BASELINE_VERSIOND_ROUTER_IMAGE:-devshard-versiond-router:0.2.15-v5}"
DEVSHARDD_BUILDER_IMAGE="${BASELINE_DEVSHARDD_BUILDER_IMAGE:-devshardd-builder:0.2.15-v5}"
CHECKOUT="${BASELINE_CHECKOUT:-${root}/devshard/testenv/baselines/checkout}"
DEVSHARDD_PATH="${BASELINE_DEVSHARDD_PATH:-${root}/devshard/testenv/baselines/devshardd-0.2.15-v5}"
PIN_FILE="${BASELINE_PIN_FILE:-${root}/devshard/testenv/baselines/0.2.15-v5.txt}"
SKIP_DEVSHARDD="${BASELINE_SKIP_DEVSHARDD:-}"

if [ "$(uname -s 2>/dev/null)" = Darwin ] && [ "$(sysctl -n hw.optional.arm64 2>/dev/null)" = 1 ]; then
	PLATFORM="${DOCKER_PLATFORM:-linux/arm64}"
else
	PLATFORM="${DOCKER_PLATFORM:-linux/amd64}"
fi
case "$PLATFORM" in
	linux/arm64*) GOARCH=arm64 ;;
	linux/amd64*) GOARCH=amd64 ;;
	*) echo "unsupported baseline devshardd platform ${PLATFORM}" >&2; exit 1 ;;
esac

resolve_ref() {
	local cand
	if [ -n "${BASELINE_REF}" ]; then
		git rev-parse --verify "${BASELINE_REF}^{commit}"
		return
	fi
	for cand in \
		"${BASELINE_BRANCH}" \
		"origin/${BASELINE_BRANCH}" \
		"upstream/${BASELINE_BRANCH}" \
		"product-science/${BASELINE_BRANCH}"; do
		if git rev-parse --verify "${cand}^{commit}" >/dev/null 2>&1; then
			echo "using ref ${cand}" >&2
			git rev-parse "${cand}^{commit}"
			return
		fi
	done
	echo "baseline ref ${BASELINE_BRANCH} not found locally; fetch upstream/${BASELINE_BRANCH}" >&2
	exit 1
}

sha="$(resolve_ref)"
echo "baseline ref ${sha} (requested ${BASELINE_REF:-${BASELINE_BRANCH}})"
echo "platform ${PLATFORM}"

rm -rf "${CHECKOUT}"
mkdir -p "${CHECKOUT}"
# versiond context is versioned/. Router and devshardd Dockerfiles COPY from
# repo root, so retain only the directories needed by those three builds.
git archive "${sha}" .dockerignore common devshard inference-chain versioned versiond-router router-runtime | tar -x -C "${CHECKOUT}"

echo "--> building ${VERSIOND_IMAGE}"
docker build --platform "${PLATFORM}" \
	--label "org.opencontainers.image.revision=${sha}" \
	--label "org.opencontainers.image.ref.name=${BASELINE_BRANCH}" \
	-t "${VERSIOND_IMAGE}" \
	-f "${CHECKOUT}/versioned/Dockerfile" \
	"${CHECKOUT}/versioned"

echo "--> building ${ROUTER_IMAGE}"
docker build --platform "${PLATFORM}" \
	--label "org.opencontainers.image.revision=${sha}" \
	--label "org.opencontainers.image.ref.name=${BASELINE_BRANCH}" \
	-t "${ROUTER_IMAGE}" \
	-f "${CHECKOUT}/versiond-router/Dockerfile" \
	"${CHECKOUT}"

if [ -n "${SKIP_DEVSHARDD}" ]; then
	mkdir -p "$(dirname "${PIN_FILE}")"
	cat >"${PIN_FILE}" <<EOF
# Generated by scripts/build-baseline-infra.sh — not a release artifact.
branch: ${BASELINE_BRANCH}
sha: ${sha}
platform: ${PLATFORM}
versiond_image: ${VERSIOND_IMAGE}
versiond_router_image: ${ROUTER_IMAGE}
built_utc: $(date -u +%Y-%m-%dT%H:%M:%SZ)
checkout: ${CHECKOUT}
EOF
	echo "wrote ${PIN_FILE}"
	docker image inspect --format '{{.RepoTags}} {{.Id}} {{index .Config.Labels "org.opencontainers.image.revision"}}' \
		"${VERSIOND_IMAGE}" "${ROUTER_IMAGE}"
	exit 0
fi

echo "--> building legacy child ${DEVSHARDD_PATH}"
docker build --platform "${PLATFORM}" --target builder \
	--label "org.opencontainers.image.revision=${sha}" \
	--label "org.opencontainers.image.ref.name=${BASELINE_BRANCH}" \
	--build-arg GOOS=linux \
	--build-arg GOARCH="${GOARCH}" \
	--build-arg DEVSHARD_VERSION=v2 \
	--build-arg DEVSHARD_BINARY_VERSION=0.2.13-v2-r2 \
	--build-arg DEVSHARD_BUILD_TAGS=devshard_testenv \
	-t "${DEVSHARDD_BUILDER_IMAGE}" \
	-f "${CHECKOUT}/devshard/Dockerfile" \
	"${CHECKOUT}"
mkdir -p "$(dirname "${DEVSHARDD_PATH}")"
cid="$(docker create "${DEVSHARDD_BUILDER_IMAGE}")"
cleanup_child_container() {
	docker rm -f "${cid}" >/dev/null 2>&1 || true
}
trap cleanup_child_container EXIT
docker cp "${cid}:/app/devshard/build/devshardd" "${DEVSHARDD_PATH}"
docker rm "${cid}" >/dev/null
trap - EXIT
chmod 0755 "${DEVSHARDD_PATH}"
DEVSHARDD_SHA256="$(shasum -a 256 "${DEVSHARDD_PATH}" | awk '{print $1}')"

mkdir -p "$(dirname "${PIN_FILE}")"
cat >"${PIN_FILE}" <<EOF
# Generated by scripts/build-baseline-infra.sh — not a release artifact.
branch: ${BASELINE_BRANCH}
sha: ${sha}
platform: ${PLATFORM}
versiond_image: ${VERSIOND_IMAGE}
versiond_router_image: ${ROUTER_IMAGE}
devshardd_path: ${DEVSHARDD_PATH}
devshardd_sha256: ${DEVSHARDD_SHA256}
built_utc: $(date -u +%Y-%m-%dT%H:%M:%SZ)
checkout: ${CHECKOUT}
EOF

echo "wrote ${PIN_FILE}"
docker image inspect --format '{{.RepoTags}} {{.Id}} {{index .Config.Labels "org.opencontainers.image.revision"}}' \
	"${VERSIOND_IMAGE}" "${ROUTER_IMAGE}" "${DEVSHARDD_BUILDER_IMAGE}"
echo "legacy child ${DEVSHARDD_PATH} sha256=${DEVSHARDD_SHA256}"
