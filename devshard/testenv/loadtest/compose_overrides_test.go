package loadtest

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
	"gopkg.in/yaml.v3"
)

const overridesFixture = `# Auto-generated by gencompose — do not edit manually.
networks:
  testenv:
    driver: bridge

services:

  mock-chain:
    image: devshard-mock-chain:latest
    environment:
      CONFIG_PATH: "/app/config.yaml"
    healthcheck:
      test: ["CMD", "wget", "-q", "-O", "-", "http://127.0.0.1:26657/health"]
    restart: unless-stopped

  versiond-0:
    image: devshard-versiond:latest
    environment:
      # Peers here are compose service names.
      DEVSHARD_RPC_ENDPOINTS: ${DEVSHARD_RPC_ENDPOINTS:-signatures,mempool,diffs,gossip,repair,height-sync,verify-timeout,verify-error-miss,challenge-receipt,payload,chat}
      GRPC_ENABLE_TXT_SERVICE_CONFIG: "true"
    depends_on:
      - mock-chain
    stop_grace_period: 30m

  devshardctl:
    image: devshard-runtime:latest
    entrypoint: ["devshardctl"]
    environment:
      DEVSHARDS_JSON: '[{"escrow_id":"1","model":"model-a","hosts":["versiond-0","versiond-1","versiond-2","versiond-3","versiond-4","versiond-5"]}]'
      DEVSHARD_PRIVATE_KEY: ${TESTENV_USER_PRIVATE_KEY}
    logging:
      driver: local

  mock-openai-0:
    image: devshard-mock-openai:latest
    environment:
      MOCK_OPENAI_WORKERS: "100"

  devshard-postgres:
    image: postgres:16-alpine
`

func TestLoadTestComposeOverrides(t *testing.T) {
	out, err := loadTestComposeOverrides([]byte(overridesFixture))
	require.NoError(t, err)

	var before, after map[string]any
	require.NoError(t, yaml.Unmarshal([]byte(overridesFixture), &before))
	require.NoError(t, yaml.Unmarshal(out, &after))
	services := after["services"].(map[string]any)
	require.Len(t, services, 5)
	for name, raw := range services {
		service := raw.(map[string]any)
		env := service["environment"].(map[string]any)
		if name == "mock-openai-0" {
			require.Equal(t, "1", env["MOCK_OPENAI_HONEST_USAGE"], "the mock ML nodes report the tokens they emitted")
		} else {
			require.NotContains(t, env, "MOCK_OPENAI_HONEST_USAGE", name)
		}
		if name == "devshardctl" {
			require.Equal(t, map[string]any{"driver": "local"}, service["logging"], "an explicit logging section is kept")
		} else {
			require.Equal(t, map[string]any{
				"driver": "json-file", "options": map[string]any{"max-size": "1g", "max-file": "3"},
			}, service["logging"], name)
		}
		// Everything else of the service is unchanged.
		orig := before["services"].(map[string]any)[name].(map[string]any)
		for k, v := range orig {
			if k == "environment" || k == "logging" {
				continue
			}
			require.Equal(t, v, service[k], "%s.%s", name, k)
		}
		if origEnv, ok := orig["environment"].(map[string]any); ok {
			for k, v := range origEnv {
				require.Equal(t, v, env[k], "%s.environment.%s", name, k)
			}
		}
	}
	require.Equal(t, before["networks"], after["networks"])
	// The long default stays on one line and the generator's comments survive.
	require.Contains(t, string(out), "challenge-receipt,payload,chat}\n")
	require.Contains(t, string(out), "# Peers here are compose service names.")
	require.True(t, strings.HasPrefix(string(out), "# Auto-generated by gencompose"))
}

func TestApplyLoadTestComposeOverridesRewritesTheFile(t *testing.T) {
	path := filepath.Join(t.TempDir(), "docker-compose.yml")
	require.NoError(t, os.WriteFile(path, []byte(overridesFixture), 0o644))
	require.NoError(t, applyLoadTestComposeOverrides(path))
	body, err := os.ReadFile(path)
	require.NoError(t, err)
	require.Contains(t, string(body), `MOCK_OPENAI_HONEST_USAGE: "1"`)
	require.Contains(t, string(body), `GRPC_ENABLE_TXT_SERVICE_CONFIG: "true"`, "the services keep their own resolver settings")
	require.Contains(t, string(body), `max-size: 1g`)
}

func TestLoadTestComposeOverridesRejectsAComposeWithoutServices(t *testing.T) {
	_, err := loadTestComposeOverrides([]byte("networks: {}\n"))
	require.Error(t, err)
}
