// BootstrapRealDAPI starts an isolated real inference-chain + decentralized-api
// pair. Mock ML and DevShard services deliberately do not appear here; their
// wiring belongs to the next two migration steps.
func BootstrapRealDAPI(ctx context.Context, cfg RealDAPIConfig) (result RealDAPIResult, err error) {
	if cfg.TestenvDir == "" || cfg.OutputDir == "" {
		return RealDAPIResult{}, fmt.Errorf("testenv directory and output directory are required")
	}
	if err := os.MkdirAll(cfg.OutputDir, 0o755); err != nil {
		return RealDAPIResult{}, fmt.Errorf("create result directory: %w", err)
	}
	workDir, err := os.MkdirTemp(cfg.TestenvDir, "loadtest-real-dapi-")
	if err != nil {
		return RealDAPIResult{}, fmt.Errorf("create local-test-net work directory: %w", err)
	}
	result.OutputDir = cfg.OutputDir
	result.WorkDir = workDir
	if !cfg.KeepStack {
		defer func() { _ = os.RemoveAll(workDir) }()
	}

	composePath, ports, err := writeRealDAPIStack(cfg.TestenvDir, workDir)
	if err != nil {
		return RealDAPIResult{}, err
	}
	if err := copyFile(composePath, filepath.Join(cfg.OutputDir, "docker-compose.yml")); err != nil {
		return RealDAPIResult{}, err
	}
	if err := copyFile(filepath.Join(workDir, "node-config.json"), filepath.Join(cfg.OutputDir, "node-config.json")); err != nil {
		return RealDAPIResult{}, err
	}

	project := "loadtest-real-dapi-" + strconv.FormatInt(time.Now().UnixNano(), 36)
	result.Project = project
	result.NodeManagerAddress = fmt.Sprintf("127.0.0.1:%d", ports.nodeManager)
	result.MLAPIURL = fmt.Sprintf("http://127.0.0.1:%d", ports.mlAPI)
	defer func() {
		if cfg.KeepStack {
			return
		}
		_ = writeComposeLogs(cfg.OutputDir, cfg.TestenvDir, project, composePath)
		_ = runCommand(context.Background(), cfg.TestenvDir, "docker", "compose", "-p", project, "-f", composePath, "down", "--volumes", "--remove-orphans")
	}()

	if err := runCommand(ctx, cfg.TestenvDir, "docker", "compose", "-p", project, "-f", composePath, "up", "--build", "--wait", "--detach"); err != nil {
		_ = writeComposeLogs(cfg.OutputDir, cfg.TestenvDir, project, composePath)
		return RealDAPIResult{}, err
	}
	if err := waitDAPI(ctx, result.MLAPIURL); err != nil {
		_ = writeComposeLogs(cfg.OutputDir, cfg.TestenvDir, project, composePath)
		return RealDAPIResult{}, err
	}
	if err := writeNodeCapacity(ctx, result.NodeManagerAddress, cfg.OutputDir); err != nil {
		_ = writeComposeLogs(cfg.OutputDir, cfg.TestenvDir, project, composePath)
		return RealDAPIResult{}, err
	}
	if err := writeComposeLogs(cfg.OutputDir, cfg.TestenvDir, project, composePath); err != nil {
		return RealDAPIResult{}, err
	}
	return result, nil
}

type realDAPIPorts struct {
	http        int
	mlAPI       int
	nodeManager int
}

func writeRealDAPIStack(testenvDir, workDir string) (string, realDAPIPorts, error) {
	repoRoot, err := filepath.Abs(filepath.Join(testenvDir, "..", ".."))
	if err != nil {
		return "", realDAPIPorts{}, err
	}
	ports := realDAPIPorts{}
	for _, target := range []*int{&ports.http, &ports.mlAPI, &ports.nodeManager} {
		port, err := freePort()
		if err != nil {
			return "", realDAPIPorts{}, err
		}
		*target = port
	}
	if err := writeRealDAPINodeConfig(filepath.Join(workDir, "node-config.json")); err != nil {
		return "", realDAPIPorts{}, err
	}
	composePath := filepath.Join(workDir, "docker-compose.yml")
	file, err := os.Create(composePath)
	if err != nil {
		return "", realDAPIPorts{}, err
	}
	defer file.Close()
	tmpl, err := template.New("real-dapi-compose").Parse(realDAPIComposeTemplate)
	if err != nil {
		return "", realDAPIPorts{}, err
	}
	if err := tmpl.Execute(file, realDAPIComposeConfig{
		RepoRoot:            repoRoot,
		GOARCH:              runtime.GOARCH,
		DAPIHTTPPort:        ports.http,
		DAPIMLPort:          ports.mlAPI,
		DAPINodeManagerPort: ports.nodeManager,
	}); err != nil {
		return "", realDAPIPorts{}, err
	}
	return composePath, ports, nil
}

func writeRealDAPINodeConfig(path string) error {
	type nodeConfig struct {
		Host             string                    `json:"host"`
		InferenceSegment string                    `json:"inference_segment"`
		InferencePort    int                       `json:"inference_port"`
		PoCSegment       string                    `json:"poc_segment"`
		PoCPort          int                       `json:"poc_port"`
		Models           map[string]map[string]any `json:"models"`
		ID               string                    `json:"id"`
		MaxConcurrent    int                       `json:"max_concurrent"`
	}
	nodes := []nodeConfig{
		{Host: "mock-openai-0", InferenceSegment: "/v1/chat/completions", InferencePort: 8088, PoCPort: 8088, Models: map[string]map[string]any{realDAPIGovernanceModel: {}}, ID: "mock-openai-0", MaxConcurrent: 100},
		{Host: "mock-openai-1", InferenceSegment: "/v1/chat/completions", InferencePort: 8088, PoCPort: 8088, Models: map[string]map[string]any{realDAPIGovernanceModel: {}}, ID: "mock-openai-1", MaxConcurrent: 100},
	}
	body, err := json.MarshalIndent(nodes, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(body, '\n'), 0o644)
}

func waitDAPI(ctx context.Context, mlAPIURL string) error {
	deadline := time.NewTimer(5 * time.Minute)
	defer deadline.Stop()
	ticker := time.NewTicker(time.Second)
	defer ticker.Stop()
	client := &http.Client{Timeout: 2 * time.Second}
	for {
		request, err := http.NewRequestWithContext(ctx, http.MethodGet, mlAPIURL+"/versions", nil)
		if err != nil {
			return err
		}
		response, err := client.Do(request)
		if err == nil {
			_ = response.Body.Close()
			if response.StatusCode == http.StatusOK {
				return nil
			}
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-deadline.C:
			return fmt.Errorf("real DAPI did not become ready within 5m")
		case <-ticker.C:
		}
	}
}

// writeNodeCapacity proves the real DAPI NodeManager gRPC server is accepting
// calls before later steps attach DevShard hosts and ML nodes to it.
func writeNodeCapacity(ctx context.Context, address, outputDir string) error {
	dialCtx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	conn, err := grpc.DialContext(dialCtx, address, grpc.WithTransportCredentials(insecure.NewCredentials()), grpc.WithBlock())
	if err != nil {
		return fmt.Errorf("dial real DAPI NodeManager: %w", err)
	}
	defer conn.Close()

	client := gen.NewNodeManagerClient(conn)
	deadline := time.NewTimer(30 * time.Second)
	defer deadline.Stop()
	var response *gen.ListNodeCapacityResponse
	for {
		rpcCtx, cancelRPC := context.WithTimeout(ctx, 5*time.Second)
		response, err = client.ListNodeCapacity(rpcCtx, &gen.ListNodeCapacityRequest{})
		cancelRPC()
		if err == nil && len(response.GetNodes()) == 2 {
			break
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-deadline.C:
			if err != nil {
				return fmt.Errorf("list real DAPI node capacity: %w", err)
			}
			return fmt.Errorf("real DAPI registered %d of 2 Mock ML nodes", len(response.GetNodes()))
		case <-time.After(time.Second):
		}
	}
	body, err := json.MarshalIndent(response, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(outputDir, "dapi-node-capacity.json"), append(body, '\n'), 0o644)
}

func realDAPIComposeHasMocks(compose string) bool {
	return strings.Contains(compose, "mock-chain") || strings.Contains(compose, "mock-dapi")
}
